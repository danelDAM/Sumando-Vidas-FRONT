export function mergePublicRows<T>(
  liveRows: T[] | null | undefined,
  fallbackRows: T[],
  getKey: (row: T) => string,
): T[] {
  const mergedRows = new Map(fallbackRows.map((row) => [getKey(row), row]));
  liveRows?.forEach((row) => mergedRows.set(getKey(row), row));
  return [...mergedRows.values()];
}

